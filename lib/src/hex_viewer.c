/*
Инициализирует структуру настроек значениями по умолчанию
 */
void init_config(HexConfig *config) {
    // Проверяем указатель на корректность, чтобы избежать падения программы
    if (config == NULL) {
        return;
    }

    // Имя файла по умолчанию пустое
    config->file_name[0] = '\0';
    
    // Имя директории по умолчанию пустое
    config->dir_name[0] = '\0';
    
    // Смещение от начала файла по умолчанию равно 0 (вывод с самого старта)
    config->offset = 0;
    
    // Лимит на объем выводимых данных по умолчанию равен -1 (выводить весь файл целиком)
    config->size = -1;
    
    // Размер одного выводимого кусочка (группы) по умолчанию равен 1 байту
    config->group_size = 1;
    
    // Количество выводимых групп в одной строке по умолчанию равно 16
    config->items_per_line = 16;
}

/*
Выполняет разбор аргументов командной строки с помощью getopt
 */
int parse_args(int argc, char *argv[], HexConfig *config) {
    // Если структура конфигурации не передана, завершаем работу с ошибкой
    if (config == NULL) {
        return -1;
    }

    // Сбрасываем глобальный индекс getopt перед каждым сканированием для безопасности
    optind = 1;
    
    // Переменная для хранения текущего считанного символа опции
    int opt;

    // Цикл разбора аргументов. Строка формата содержит поддерживаемые ключи.
    // Двоеточие после буквы (например, 'i:') означает обязательный параметр.
    while ((opt = getopt(argc, argv, "i:o:l:g:n:d:h")) != -1) {
        switch (opt) {
            case 'i':
                // Безопасно копируем имя входного файла в структуру настроек
                strncpy(config->file_name, optarg, MAX_PATH_LEN - 1);
                // Принудительно устанавливаем нуль-терминатор в конец строки для защиты от переполнения
                config->file_name[MAX_PATH_LEN - 1] = '\0';
                break;

            case 'd':
                // Безопасно копируем имя целевой директории
                strncpy(config->dir_name, optarg, MAX_PATH_LEN - 1);
                // Обеспечиваем корректное завершение строки нулем
                config->dir_name[MAX_PATH_LEN - 1] = '\0';
                break;

            case 'o':
                // Преобразуем строку смещения в число типа long. 
                // Третий аргумент "0" позволяет автоматически распознавать hex (0x10) и dec (16) форматы.
                config->offset = strtol(optarg, NULL, 0);
                // Смещение от начала файла не может иметь отрицательное значение
                if (config->offset < 0) {
                    fprintf(stderr, "Ошибка: Смещение (-o) должно быть неотрицательным числом.\n");
                    return -1;
                }
                break;

            case 'l':
                // Преобразуем строку размера в число long
                config->size = strtol(optarg, NULL, 0);
                // Количество байт для вывода должно быть строго больше нуля
                if (config->size <= 0) {
                    fprintf(stderr, "Ошибка: Количество выводимых байт (-l) должно быть больше 0.\n");
                    return -1;
                }
                break;

            case 'g':
                // Считываем размер кусочка (группы)
                config->group_size = (int)strtol(optarg, NULL, 0);
                // Минимальный размер кусочка равен 1 байту
                if (config->group_size <= 0) {
                    fprintf(stderr, "Ошибка: Размер кусочка (-g) должен быть больше 0.\n");
                    return -1;
                }
                break;

            case 'n':
                // Считываем количество кусочков в одной строке вывода
                config->items_per_line = (int)strtol(optarg, NULL, 0);
                // В строке должен быть выведен хотя бы один кусочек
                if (config->items_per_line <= 0) {
                    fprintf(stderr, "Ошибка: Количество элементов в строке (-n) должно быть больше 0.\n");
                    return -1;
                }
                break;

            case 'h':
                // При запросе справки выводим инструкцию и возвращаем маркер неудачи,
                // чтобы приложение не продолжало выполнять основную логику.
                printf("Использование программы Hex-Viewer:\n");
                printf("  %s -i <file_name> [опции]\n", argv[0]);
                printf("  %s -d <dir_name>  [опции]\n", argv[0]);
                printf("Доступные опции:\n");
                printf("  -o <offset>  Смещение от начала файла (по умолчанию: 0)\n");
                printf("  -l <size>    Количество байт для вывода (по умолчанию: весь файл)\n");
                printf("  -g <size>    Размер кусочка данных в байтах (по умолчанию: 1)\n");
                printf("  -n <count>   Количество кусочков в одной строке (по умолчанию: 16)\n");
                return -1;

            default:
                // В случае неизвестного флага сообщаем об ошибке
                fprintf(stderr, "Неизвестная или неверно заданная опция. Используйте -h для справки.\n");
                return -1;
        }
    }

    // Проверяем валидность сочетания параметров: пользователь должен задать либо файл, либо директорию
    if (config->file_name[0] == '\0' && config->dir_name[0] == '\0') {
        fprintf(stderr, "Ошибка: Необходимо обязательно указать файл (-i) или директорию (-d).\n");
        return -1;
    }

    // Возвращаем 0, если все параметры успешно считаны и прошли валидацию
    return 0;
}

/*
Функция: print_hex_byte_manual
Назначение: Переводит один байт в два шестнадцатеричных символа и выводит их на экран.
Выполняется вручную через битовые операции без использования printf("%x").
Параметры:
 - byte: значение байта для вывода
 */
void print_hex_byte_manual(unsigned char byte) {
    // Таблица соответствия полубайта шестнадцатеричному символу в верхнем регистре
    const char hex_chars[] = "0123456789ABCDEF";

    // Сдвигаем байт на 4 бита вправо и накладываем маску 0x0F (00001111),
    // чтобы получить значение старшего полубайта (high nibble)
    char high_char = hex_chars[(byte >> 4) & 0x0F];

    // Накладываем маску 0x0F на исходный байт,
    // чтобы получить значение младшего полубайта (low nibble)
    char low_char = hex_chars[byte & 0x0F];

    // Выводим полученные символы поочередно через разрешенный %c
    printf("%c%c", high_char, low_char);
}

/*
Функция: print_ascii_char_manual
Назначение: Выводит символ, если он является печатным (printable) в кодировке ASCII.
Если символ непечатный (управляющий или за пределами ASCII), выводит точку '.'.
Параметры:
 - byte: значение байта для анализа и вывода
 */
void print_ascii_char_manual(unsigned char byte) {
    // В стандартной таблице ASCII печатные символы находятся в диапазоне от 32 (пробел) до 126 (тильда '~')
    if (byte >= 32 && byte <= 126) {
        // Выводим сам символ
        printf("%c", byte);
    } else {
        // Вместо непечатного символа или нулевого байта выводим точку
        printf(".");
    }
}

/*
Функция: process_file
Назначение: Читает файл, форматирует и выводит его содержимое в шестнадцатеричном виде.
Поддерживает смещение, ограничение по размеру и вывод ASCII символов (при -g 1).
 */
int process_file(const HexConfig *config, const char *filepath) {
    // Проверяем входные указатели на валидность
    if (config == NULL || filepath == NULL) {
        return -1;
    }

    // Открываем целевой файл в безопасном двоичном (бинарном) режиме "rb"
    FILE *file = fopen(filepath, "r");
    if (file == NULL) {
        // Если открыть файл не удалось, выводим ошибку в поток ошибок stderr
        fprintf(stderr, "Ошибка: Не удалось открыть файл '%s'.\n", filepath);
        return -1;
    }

    // Позиционируем указатель чтения на заданное смещение от начала файла (SEEK_SET)
    if (config->offset > 0) {
        // fseek возвращает ненулевое значение при ошибке (например, смещение больше файла)
        if (fseek(file, config->offset, SEEK_SET) != 0) {
            fprintf(stderr, "Ошибка: Не удалось перейти на смещение %ld в файле '%s'.\n", config->offset, filepath);
            fclose(file); // Обязательно закрываем файл перед выходом
            return -1;
        }
    }

    // Текущее смещение от начала файла для вывода в левом столбце
    long current_offset = config->offset;
    
    // Счётчик общего количества байт, которые мы уже прочитали и вывели
    long total_bytes_read = 0;

    // Выделяем динамический буфер под чтение одной полной строки вывода.
    // Максимальный размер строки в байтах равен: количество элементов на строку * размер элемента
    int bytes_per_line = config->items_per_line * config->group_size;
    unsigned char *line_buffer = (unsigned char *)malloc(bytes_per_line);
    if (line_buffer == NULL) {
        fprintf(stderr, "Ошибка: Не удалось выделить память под буфер чтения.\n");
        fclose(file);
        return -1;
    }

    // Флаг для контроля завершения основного цикла чтения
    int stop_reading = 0;

    // Основной цикл чтения файла построчно
    while (!stop_reading) {
        // Определяем, сколько байт нам осталось прочитать с учётом лимита (-l)
        int bytes_to_read = bytes_per_line;
        if (config->size != -1) {
            long remaining = config->size - total_bytes_read;
            // Если оставшийся лимит меньше, чем вместимость одной строки, уменьшаем размер чтения
            if (remaining < bytes_per_line) {
                bytes_to_read = (int)remaining;
            }
            // Если лимит полностью исчерпан, останавливаем чтение
            if (bytes_to_read <= 0) {
                break;
            }
        }

        // Читаем блок данных из файла в наш буфер строки.
        // fread возвращает реальное количество успешно прочитанных байт
        size_t actual_read = fread(line_buffer, 1, bytes_to_read, file);
        
        // Если ничего не прочитано (достигнут конец файла), завершаем цикл
        if (actual_read == 0) {
            break;
        }

        // 1: ВЫВОД СМЕЩЕНИЯ (АДРЕСА СТРОКИ)
        // Смещение разрешено выводить через printf со спецификатором %x (в hex-формате, дополняя нулями до 8 знаков)
        printf("%08lx  ", current_offset);

        // 2: ВЫВОД ДАННЫХ В HEX (БАЗОВЫЙ ВАРИАНТ -g 1)
        // Обрабатываем пока только базовый случай, когда размер группы равен 1 байту
        if (config->group_size == 1) {
            // Печатаем hex-представление каждого байта строки
            for (size_t i = 0; i < actual_read; i++) {
                print_hex_byte_manual(line_buffer[i]);
                printf(" "); // Разделяем байты пробелом
            }

            // 3: ВЫРАВНИВАНИЕ (ПРОБЕЛЫ) ДЛЯ НЕПОЛНОЙ СТРОКИ
            // Если это последняя строка файла и она неполная, нам нужно вывести пробелы,
            // чтобы символьный столбец справа не съехал влево.
            for (size_t i = actual_read; i < (size_t)bytes_per_line; i++) {
                printf("   "); // Три пробела на каждый отсутствующий байт (2 под hex-символа + пробел-разделитель)
            }

            // ШАГ 4: СИМВОЛЬНЫЙ СТОЛБЕЦ
            printf("| ");
            for (size_t i = 0; i < actual_read; i++) {
                print_ascii_char_manual(line_buffer[i]);
            }
        }

        // Переводим курсор вывода на новую строку
        printf("\n");

        // Увеличиваем счётчики прочитанных байт и текущего смещения
        total_bytes_read += actual_read;
        current_offset += actual_read;

        // Если прочитано меньше, чем мы запрашивали у fread, значит, достигнут конец файла
        if (actual_read < (size_t)bytes_to_read) {
            stop_reading = 1;
        }
    }

    // Освобождаем выделенную память и закрываем дескриптор файла
    free(line_buffer);
    fclose(file);

    return 0;
}