#ifndef HEX_VIEWER_H
#define HEX_VIEWER_H

// Подключаем стандартный заголовок для типа size_t
#include <stddef.h>

// Максимально допустимая длина путей к файлам и директориям в буферах
#define MAX_PATH_LEN 1024

/*
Структура HexConfig
Служит для хранения всех параметров конфигурации программы, 
переданных пользователем через аргументы командной строки.
 */
typedef struct {
    char file_name[MAX_PATH_LEN]; // Хранилище для пути к входному файлу (опция -i)
    char dir_name[MAX_PATH_LEN];  // Хранилище для пути к директории (опция -d)
    long offset;                  // Смещение в байтах от начала файла (опция -o, по умолчанию 0)
    long size;                    // Лимит на количество выводимых байт (опция -l, по умолчанию -1 — весь файл)
    int group_size;               // Размер одного выводимого кусочка в байтах (опция -g, по умолчанию 1)
    int items_per_line;           // Кол-во кусочков (групп), выводимых в одной строке (опция -n, по умолчанию 16)
} HexConfig;

/*
Функция: init_config
Назначение: Заполняет структуру HexConfig значениями по умолчанию.
Параметры:
 - config: указатель на инициализируемую структуру настроек
 */
void init_config(HexConfig *config);

/*
Функция: parse_args
Назначение: Разбирает аргументы командной строки с помощью getopt 
и валидирует корректность введенных значений.
Параметры:
 - argc: количество аргументов командной строки
 - argv: массив строк-аргументов
 - config: указатель на структуру, куда запишутся настройки
Возвращаемое значение:
 0 при успешном разборе,
 -1 при обнаружении ошибок в параметрах или вызове справки.
 */
int parse_args(int argc, char *argv[], HexConfig *config);

/*
Функция: process_file
Назначение: Открывает указанный файл, позиционирует указатель чтения, 
читает данные и выводит их на экран в шестнадцатеричном 
и (при необходимости) символьном виде.
Параметры:
 - config: указатель на конфигурацию с параметрами вывода (-o, -l, -g, -n)
 - filepath: полный или относительный путь к файлу
Возвращаемое значение:
 0 при успешной обработке,
 -1 при ошибках чтения или открытия файла.
 */
int process_file(const HexConfig *config, const char *filepath);

/*
Функция: process_directory
Назначение: Выполняет обход указанной директории и последовательно
вызывает функцию process_file для каждого найденного файла.
Параметры:
 - config: указатель на конфигурацию (содержит путь к директории в dir_name)
Возвращаемое значение:
 0 при успешном обходе,
 -1 при невозможности открыть или прочитать директорию.
 */
int process_directory(const HexConfig *config);

// Вспомогательная функция ручного вывода байта в HEX формате
void print_hex_byte_manual(unsigned char byte);

// Вспомогательная функция ручного вывода ASCII-символа
void print_ascii_char_manual(unsigned char byte);

#endif // HEX_VIEWER_H