/*
Точка входа в программу Hex-Viewer.
Выполняет инициализацию настроек, парсинг аргументов командной строки
и запускает процесс вывода одного файла либо обхода всей директории.

Коликов Глеб Александрович
МК-101
*/

#include <stdio.h>       // Подключаем стандартный ввод-вывод
#include <stdlib.h>      // Подключаем стандартную библиотеку
#include "hex_viewer.h"  // Подключаем интерфейс нашей библиотеки hex_lib

/*
 * Главная функция программы
 */
int main(int argc, char *argv[], char *envp[]) {
    // Неиспользуемый параметр envp явно помечаем, чтобы избежать предупреждений компилятора
    (void)envp;

    // Объявляем структуру для хранения настроек программы
    HexConfig config;

    // Инициализируем настройки значениями по умолчанию
    init_config(&config);

    // Выполняем разбор параметров командной строки с помощью parse_args.
    // Если функция вернула ненулевое значение, значит произошла ошибка или вызвана справка (-h).
    if (parse_args(argc, argv, &config) != 0) {
        // Завершаем работу с кодом возврата 1 (ошибка)
        return EXIT_FAILURE;
    }

    // Если в настройках было указано имя директории, обрабатываем её
    if (config.dir_name[0] != '\0') {
        // Запускаем обход директории
        if (process_directory(&config) != 0) {
            // Если при обходе возникли проблемы, возвращаем код ошибки
            return EXIT_FAILURE;
        }
    } 
    // В противном случае, если указан конкретный файл, обрабатываем его
    else if (config.file_name[0] != '\0') {
        // Запускаем форматированный вывод для одиночного файла
        if (process_file(&config, config.file_name) != 0) {
            // Если файл не удалось прочитать или открыть, возвращаем код ошибки
            return EXIT_FAILURE;
        }
    }

    // При успешном завершении всей логики возвращаем 0
    return EXIT_SUCCESS;
}